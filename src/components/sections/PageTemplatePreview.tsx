/**
 * Folds a staged page's per-section style overrides onto the section the
 * template saved.
 *
 * An override is stored as a `style.*` meta field whose empty value means
 * "inherit", so this only replaces an axis the editor actually set. Applying it
 * here - rather than at each of the ~40 render cases - means the section frame,
 * the component props, and the site export all read the same resolved value.
 * Resolving an already-resolved section is a no-op, so it is safe to call on
 * both paths.
 */
export function resolveSectionStyleOverrides(
  section: PageTemplatePreviewSection,
  fields: StagedPageField[] = [],
): PageTemplatePreviewSection {
  if (fields.length === 0) {
    return section;
  }

  const overrides = getSectionStyleFieldSpecs(section.component).reduce<
    Record<string, string | boolean>
  >((resolved, spec) => {
    const value = fields
      .find((field) => field.path.endsWith(`.${styleFieldPrefix}.${spec.name}`))
      ?.value.trim();

    // `isValidStyleFieldValue` is what reconciles the two spec shapes - an
    // enumerated axis is checked against its list, a continuous one against its
    // predicate - so this fold does not have to know which it is holding.
    if (value && isValidStyleFieldValue(spec, value)) {
      // The spacing fields are stored as booleans on the section. Spreading the
      // raw option string would make "default" truthy and reduce the padding it
      // was chosen to restore.
      resolved[spec.name] = booleanStyleFields.has(spec.name)
        ? value === "reduced"
        : value;
    }

    return resolved;
  }, {});

  return Object.keys(overrides).length > 0
    ? { ...section, ...overrides }
    : section;
}

function isNavigationSection(section: PageTemplatePreviewSection) {
  return section.mode === "Navigation";
}

function isHeroSection(section: PageTemplatePreviewSection | undefined) {
  return section?.mode === "Hero";
}

/** What a caller that supplies no palette gets. See the `palette` prop on
 *  `TemplateSectionFrame` for why this is a default rather than a lookup. */
const coldStartPalette = toColorPalette(coldStartTokens);

export function PageTemplatePreview({
  fieldsBySection = {},
  fixedNavigation = false,
  homeHref,
  navigationLinks = [],
  overlayNavigation = true,
  palette = coldStartPalette,
  sections,
  siteIdentity = emptySiteIdentity,
}: PageTemplatePreviewProps) {
  const includedSections = sections
    .filter(Boolean)
    .map((section) =>
      resolveSectionStyleOverrides(section, fieldsBySection[section.id ?? ""]),
    );
  const bands = groupSectionsIntoBands(includedSections);

  function renderSection(
    section: PageTemplatePreviewSection,
    index: number,
    frameProps: {
      className?: string;
      inBand?: boolean;
      isFixed?: boolean;
      isOverlay?: boolean;
    } = {},
  ) {
    return (
      <TemplateSectionFrame
        backgroundImage={
          frameProps.inBand
            ? undefined
            : backgroundLayerStyle(section, fieldsBySection[section.id ?? ""])
        }
        key={section.id ?? index}
        palette={palette}
        section={section}
        {...frameProps}
      >
        {renderPageTemplateSection(
          section,
          index,
          fieldsBySection[section.id ?? ""],
          navigationLinks,
          homeHref,
          siteIdentity,
        )}
      </TemplateSectionFrame>
    );
  }

  /**
   * A run of one renders as a bare frame, which is what every page that uses no
   * bands is made of - so this path emits exactly the DOM it did before bands
   * existed. A longer run gets the wrapper, which becomes the paint surface:
   * it carries the recipe, and its members are made inert by `inBand` so their
   * frames neither paint nor re-run the recipe's token rewrite.
   */
  function renderBand(band: SectionBand<PageTemplatePreviewSection>) {
    const [first] = band.sections;

    if (!band.isBand) {
      return renderSection(first, band.startIndex);
    }

    return (
      <div
        className="pagebuilder-section-band pagebuilder-paint-surface"
        data-pagebuilder-background-treatment={resolveBackgroundTreatment(
          first.backgroundTreatment,
        )}
        data-pagebuilder-color-recipe={
          resolveSectionColorRecipe(first.colorRecipe) ?? "page"
        }
        key={`band-${first.id ?? band.startIndex}`}
        // The run's first section supplies the image and the tuned gradient,
        // the same section that supplies the band's recipe and texture.
        style={backgroundLayerStyle(first, fieldsBySection[first.id ?? ""])}
      >
        <BackgroundTreatmentOverlay
          treatment={resolveBackgroundTreatment(first.backgroundTreatment)}
        />
        {withBandRecipe(band).map((section, offset) =>
          renderSection(section, band.startIndex + offset, { inBand: true }),
        )}
      </div>
    );
  }

  function isNavigationBand(band: SectionBand<PageTemplatePreviewSection> | undefined) {
    return Boolean(
      band && band.sections.length === 1 && isNavigationSection(band.sections[0]),
    );
  }

  return (
    <div
      className={cx(
        "page-template-preview pagebuilder-density-normal pagebuilder-hide-markers min-h-full w-full bg-bg-page",
        fixedNavigation && "page-template-preview-fixed-nav",
      )}
    >
      <div className="min-h-full w-full bg-bg-page">
        {bands.map((band, bandIndex) => {
          const [first] = band.sections;
          const nextBand = bands[bandIndex + 1];
          const previousBand = bands[bandIndex - 1];

          // Navigation never joins a band, so a nav run is always a single
          // section - see `navigationComponents`. That is what lets the pair
          // wrapper below hold a nav frame beside a whole run without nesting
          // two wrappers around the same element.
          if (isNavigationBand(band) && nextBand && isHeroSection(nextBand.sections[0])) {
            return (
              <div
                className="pagebuilder-nav-hero-pair relative"
                key={`${first.id ?? band.startIndex}-pair`}
              >
                {renderSection(first, band.startIndex, {
                  className: fixedNavigation
                    ? "inset-x-0 top-0 z-50"
                    : overlayNavigation
                      ? "inset-x-0 top-0 z-20"
                      : undefined,
                  isFixed: fixedNavigation,
                  isOverlay: !fixedNavigation && overlayNavigation,
                })}
                {renderBand(nextBand)}
              </div>
            );
          }

          if (isNavigationBand(previousBand) && isHeroSection(first)) {
            return null;
          }

          // No spacer under a nav that is followed by a non-hero section - see
          // the same branch in `PagebuilderShell`. The nav pins and reserves its
          // own height, so the margin only opened a gap the built page does not
          // have.
          if (isNavigationBand(band) && nextBand) {
            return renderSection(first, band.startIndex);
          }

          return renderBand(band);
        })}
      </div>
    </div>
  );
}

/**
 * Resolved rather than read straight off the section: a template saved before
 * its component stopped offering section spacing still carries the boolean, and
 * with the control gone there would be no way to turn it back off. Applying the
 * same rule the editor uses to offer the control keeps the two in step, on both
 * the preview and the export.
 */
function resolvePaddingAttribute(
  section: PageTemplatePreviewSection,
  edge: "top" | "bottom",
) {
  const reduce =
    edge === "top" ? section.reduceTopPadding : section.reduceBottomPadding;

  return reduce && sectionSupportsSectionSpacing(section.component)
    ? "none"
    : "default";
}

/**
 * The inline custom property that carries a ground image into the stylesheet.
 *
 * Returned as a style object rather than a `background-image` declaration so the
 * image composes with the other treatments instead of competing with them: all
 * five paint the same `::before`, and only the source of this one is per-section
 * data. Empty when there is no image, so nothing is set at all.
 */
function backgroundImageStyle(
  section: PageTemplatePreviewSection,
  treatment: string,
  fields: StagedPageField[] = [],
): CSSProperties {
  if (!treatmentUsesGroundImage(treatment)) {
    return {};
  }

  const source = resolveBackgroundImage(
    getAssetValue({ fields }, "backgroundImage", ""),
  );

  return source
    ? ({
        "--section-background-image": `url("${source}")`,
        // Fit and focal point come off the already-resolved section, so a staged
        // override has been folded on before this runs.
        ...buildBackgroundImageStyle(
          section.backgroundImageFit,
          section.backgroundImageFocus,
        ),
      } as CSSProperties)
    : {};
}

/**
 * Everything a frame or band needs to paint its ground, as one style object.
 *
 * The image and the tuned gradient are separate features that happen to share a
 * destination, so they are resolved separately and merged here rather than each
 * call site remembering both. A section carrying neither yields `{}` and sets
 * no properties at all, which is what leaves the stylesheet's defaults intact.
 */
function backgroundLayerStyle(
  section: PageTemplatePreviewSection,
  fields: StagedPageField[] = [],
): CSSProperties {
  const treatment = resolveBackgroundTreatment(section.backgroundTreatment);
  const config = resolveBackgroundConfig(section.backgroundConfig);

  return {
    ...backgroundImageStyle(section, treatment, fields),
    ...(config ? buildBackgroundConfigStyle(config) : {}),
  } as CSSProperties;
}

function TemplateSectionFrame({
  backgroundImage,
  children,
  className,
  inBand = false,
  isFixed = false,
  isOverlay = false,
  palette = coldStartPalette,
  section,
}: {
  /** Inline custom property carrying the ground image, if this frame has one. */
  backgroundImage?: CSSProperties;
  children: React.ReactNode;
  className?: string;
  /**
   * True for every member of a background band. The band is the paint surface,
   * so its members must be inert in two ways: they must not paint a ground of
   * their own, and they must not re-run the recipe's token rewrite. The recipe
   * rules are written as "capture on the container, rewrite on the children",
   * so a member that kept a live recipe value would apply the rewrite a second
   * time and compound every `color-mix` - muted text mixed twice, borders mixed
   * twice - against a ground that had already been remapped.
   */
  inBand?: boolean;
  isFixed?: boolean;
  isOverlay?: boolean;
  /**
   * The palette card polarity is measured against.
   *
   * Passed in rather than read here, and the reason is a build constraint
   * worth stating: this module is reachable from `"use client"` components, so
   * anything it imports is bundled for the browser. Reading the promoted block
   * off disk would pull `node:fs` into a client chunk and fail the Turbopack
   * build outright - which is exactly what happened when this was wired the
   * obvious way. `promoted-palette.test.ts` now walks the import graph to stop
   * it happening again.
   *
   * So each caller supplies the palette by whichever route its environment
   * allows: the server pages read `globals.css`, client surfaces read the live
   * custom properties out of the DOM. The default is cold start, which renders
   * a correct page with possibly one wrong text polarity rather than no page.
   */
  palette?: ColorPalette;
  section: PageTemplatePreviewSection;
}) {
  return (
    <div
      className={cx(
        "pagebuilder-section-frame pagebuilder-paint-surface group/pagebuilder-section outline outline-0 outline-offset-0 transition-shadow",
        isFixed ? "fixed" : isOverlay ? "absolute" : "relative",
        className,
      )}
      data-pagebuilder-background-fill={
        // Reuses the existing transparency mechanism rather than inventing one:
        // this attribute already zeroes both background-color and
        // background-image on a frame.
        inBand ? "none" : resolveBackgroundFill(section.backgroundFill)
      }
      data-pagebuilder-border-tone={resolveBorderTone(section.borderTone)}
      data-pagebuilder-card-border={resolveCardBorder(
        section.component,
        section.cardBorder,
      )}
      data-pagebuilder-card-fill={resolveCardFill(
        section.component,
        section.cardFill,
      )}
      data-pagebuilder-card-style={
        sectionSupportsCardStyle(section.component) ? "true" : "false"
      }
      {...sectionColorOverrideAttributes(section, palette)}
      data-pagebuilder-background-treatment={
        // The band owns the texture for its run, so a member never draws its
        // own - two stacked layers would double the wash.
        inBand ? "none" : resolveBackgroundTreatment(section.backgroundTreatment)
      }
      // Deliberately NOT taking the `inBand` decision the treatment above
      // takes. A texture is paint, and one band paints once; an entrance is a
      // property of the content, and band members keep their own contents. The
      // band element has none of its own, so deferring to it would mean a
      // joined section could never animate.
      data-pagebuilder-animation={resolveSectionAnimation(section.animation)}
      // Beside the entrance and taking the same decision it takes: a band
      // shares a ground, not a call to action, so a joined section keeps its
      // own answer here.
      data-pagebuilder-special-cta={resolveSpecialCta(section.specialCta)}
      data-pagebuilder-color-recipe={
        inBand
          ? "inherit"
          : (resolveSectionColorRecipe(section.colorRecipe) ?? "page")
      }
      data-pagebuilder-section-component={section.component}
      data-pagebuilder-section-mode={section.mode}
      data-pagebuilder-padding-bottom={resolvePaddingAttribute(
        section,
        "bottom",
      )}
      data-pagebuilder-padding-top={resolvePaddingAttribute(section, "top")}
      style={backgroundImage}
    >
      {/* Sits beside the treatment attribute above and takes the same `inBand`
          decision, so a member never draws a second set of sprites over the
          band's own. */}
      <BackgroundTreatmentOverlay
        treatment={
          inBand ? "none" : resolveBackgroundTreatment(section.backgroundTreatment)
        }
      />
      {children}
    </div>
  );
}

