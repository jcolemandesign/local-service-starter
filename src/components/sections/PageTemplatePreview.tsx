function getIndexedRecordValues(
  record: Record<string, string>,
  collectionName: string,
) {
  const prefix = `${collectionName.toLowerCase()}.`;

  return Object.entries(record)
    .filter(([key, value]) =>
      key.toLowerCase().startsWith(prefix) && value.trim().length > 0,
    )
    .sort(([leftKey], [rightKey]) => {
      const leftIndex = Number(leftKey.slice(prefix.length).split(".")[0]);
      const rightIndex = Number(rightKey.slice(prefix.length).split(".")[0]);

      return leftIndex - rightIndex;
    })
    .map(([, value]) => value.trim());
}

function getIndexedRecordPairs(
  record: Record<string, string>,
  collectionName: string,
  labelKey: string,
  valueKey: string,
) {
  const prefix = `${collectionName.toLowerCase()}.`;
  const indexes = new Set<number>();

  Object.keys(record).forEach((key) => {
    if (!key.toLowerCase().startsWith(prefix)) {
      return;
    }

    const index = Number(key.slice(prefix.length).split(".")[0]);

    if (Number.isFinite(index)) {
      indexes.add(index);
    }
  });

  return Array.from(indexes)
    .sort((left, right) => left - right)
    .map((index) => ({
      label: record[`${collectionName}.${index}.${labelKey}`]?.trim() ?? "",
      value: record[`${collectionName}.${index}.${valueKey}`]?.trim() ?? "",
    }))
    .filter((item) => item.label && item.value);
}

function cardItems(section: FieldSection, fieldNames: string[]) {
  const records = getCardContentRecords(section, fieldNames);

  if (records.length > 0) {
    return records.map((record) => ({
      body: record.body ?? record.description ?? "",
      cardSize: record.cardSize ?? record.size ?? record.featured,
      href: record.href,
      imageLabel: record.imageLabel ?? record.title ?? "Service",
      size: getCardSize(record.size ?? record.cardSize ?? record.featured),
      title: record.title ?? record.heading ?? "Service",
    }));
  }

  for (const fieldName of fieldNames) {
    const value = getValue(section, fieldName, "");

    if (value) {
      return splitItems(value).map(parseCardItem);
    }
  }

  return [];
}

