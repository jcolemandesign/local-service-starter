function projectCaseStudyGalleryProps(section: FieldSection) {
  const structuredSlides = getRepeatedRecords(section, ["slides"]);
  const assetSlides = getRepeatedAssetRecords(section, ["slides"]);
  const fallbackSlides = sectionLibraryV3Content.projectCaseStudyGallery.slides;
  const hasStagedContent = section.fields.some(
    (field) => field.kind === "copy" && field.value.trim().length > 0,
  );

  if (!hasStagedContent) {
    return sectionLibraryV3Content.projectCaseStudyGallery;
  }

  return {
    slides: structuredSlides.flatMap((slide, index) => {
      const equipment = getIndexedRecordPairs(
        slide,
        "equipment",
        "label",
        "value",
      );

      if (!isQualifiedProjectCaseStudySlide(slide, equipment)) {
        return [];
      }

      const testimonialQuote = getApprovedProjectValue(
        slide["testimonial.quote"],
      );
      const testimonialAttribution = getApprovedProjectValue(
        slide["testimonial.attribution"],
      );
      const fallbackSlide = fallbackSlides[index % fallbackSlides.length];
      const assetSlide = assetSlides[index];
      const imageSrc = assetSlide?.imageSrc ?? fallbackSlide.imageSrc;
      // The library's intrinsic dimensions describe the library's image. Once a
      // staged page points at a different file they describe nothing, and
      // passing them on would frame the print to the wrong ratio until the
      // browser corrected it - a visible jump. Carry them only for the image
      // they were measured from.
      const usesFallbackImage = imageSrc === fallbackSlide.imageSrc;

      return [
        {
          equipment,
          imageAlt: assetSlide?.imageAlt ?? fallbackSlide.imageAlt,
          imageHeight: usesFallbackImage ? fallbackSlide.imageHeight : undefined,
          imageSrc,
          imageWidth: usesFallbackImage ? fallbackSlide.imageWidth : undefined,
          project: slide.project,
          summary: slide.summary,
          testimonial: {
            attribution:
              testimonialQuote && testimonialAttribution
                ? testimonialAttribution
                : "",
            quote:
              testimonialQuote && testimonialAttribution
                ? testimonialQuote
                : "",
          },
          title: slide.title,
        },
      ];
    }),
  };
}

function isQualifiedProjectCaseStudySlide(
  slide: Record<string, string>,
  equipment: Array<{ label: string; value: string }>,
) {
  return (
    Boolean(getApprovedProjectValue(slide.project)) &&
    Boolean(getApprovedProjectValue(slide.title)) &&
    Boolean(getApprovedProjectValue(slide.summary)) &&
    equipment.length === 3 &&
    equipment.every(
      (detail) =>
        Boolean(getApprovedProjectValue(detail.label)) &&
        Boolean(getApprovedProjectValue(detail.value)),
    )
  );
}

function getApprovedProjectValue(value: string | undefined) {
  const normalizedValue = value?.trim() ?? "";

  return normalizedValue && !/needs review/i.test(normalizedValue)
    ? normalizedValue
    : "";
}

